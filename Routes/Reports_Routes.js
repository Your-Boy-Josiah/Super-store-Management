const router = require("express").Router();
const controller = require("../Controllers/Report_Controller");
const { verifyToken } = require("../Middleware/Auths");
const { authorizeReport } = require("../Middleware/Reports");
router.use(verifyToken, authorizeReport);
router.get("/dashboard-summary", controller.GetDashboardSummary);
router.get("/revenue-trend", controller.GetRevenueTrend);
router.get("/alerts", controller.GetAlerts);
router.get("/top-sellers", controller.GetTopSellers);
module.exports = router;
